// Generates src/StartupKb.cs from a researched JSON knowledge base (array of
// {kind, match, label, purpose, verdict, effect, source}). Refuses non-ASCII text and unknown verdicts.
// Usage: node tools/gen-startup-kb.mjs <kb.json>
import { readFileSync, writeFileSync } from 'node:fs';
const kb = JSON.parse(readFileSync(process.argv[2], 'utf8'));
const verdicts = { safe: 'Safe', caution: 'Caution', keep: 'Keep' };
const lit = (s) => {
  if (s == null) return 'null';
  if (!/^[\x20-\x7e]*$/.test(s)) throw new Error('non-ASCII or control character in: ' + s);
  return JSON.stringify(s); // ASCII JSON string literals are valid C# string literals
};
const seen = new Set();
const rows = kb.map((e) => {
  if (e.kind !== 'app' && e.kind !== 'service') throw new Error('bad kind: ' + e.match);
  if (!verdicts[e.verdict]) throw new Error('bad verdict: ' + e.match);
  const key = e.kind + ':' + e.match.toLowerCase();
  if (seen.has(key)) throw new Error('duplicate: ' + key);
  seen.add(key);
  return '                new KnownItem(' + (e.kind === 'service') + ', ' + lit(e.match) + ', ' + lit(e.label) + ', '
    + lit(e.purpose) + ', Verdict.' + verdicts[e.verdict] + ', ' + lit(e.effect) + '),';
});
const out = `// Generated by tools/gen-startup-kb.mjs from researched entries. Do not edit by hand.
// Sources were cited where an official page exists; the rest use conservative wording.
namespace RamOptimiser
{
    public static partial class StartupKnowledge
    {
        static KnownItem[] BuildEntries()
        {
            return new[]
            {
${rows.join('\n')}
            };
        }
    }
}
`;
writeFileSync(new URL('../src/StartupKb.cs', import.meta.url), out);
console.log('wrote ' + rows.length + ' entries');
